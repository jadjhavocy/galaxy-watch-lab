import assert from 'node:assert/strict';
import {GestureEngine} from '../motion/engine.mjs';
import {ControlRouter,MUSIC_COMMANDS} from '../motion/control_router.mjs';
import {VirtualPlayer} from '../motion/virtual_player.mjs';
const evt=(ns,axis='X',direction='positive')=>({type:'wrist_flick',timestamp_ns:ns,axis,direction,peak_rads:3.3});
const r=new ControlRouter();
assert.equal(r.accept(evt(1),1000).reason,'not_armed');
assert.equal(r.arm(1200,'browser').reason,'wrong_context');
assert.equal(r.accept(evt(2),1300).reason,'not_armed');
assert.equal(r.arm(1400).status,'armed');
assert.equal(r.accept(evt(3),1500,'desktop').reason,'wrong_context');
assert.equal(r.accept(evt(4),1600).command,'NEXT');
assert.equal(r.accept(evt(5),1700).reason,'not_armed');
assert.equal(r.arm(1800).status,'armed');
assert.equal(r.accept(evt(6),1900).reason,'cooldown');
assert.equal(r.accept(evt(6),2000).reason,'duplicate_or_stale');
assert.equal(r.accept(evt(7),2600).command,'NEXT');
assert.equal(r.arm(4000).status,'armed');
assert.equal(r.accept(evt(8),15000).reason,'arm_expired');
assert.equal(r.accept(evt(9),15100).reason,'not_armed');
assert.equal(r.arm(16000).status,'armed');
assert.equal(r.accept(evt(10,'Z','negative'),16100).status,'cancelled');
assert.equal(r.accept(evt(11),16200).reason,'not_armed');
assert.equal(r.arm(18000).status,'armed');
assert.equal(r.accept(evt(12,'W','positive'),18100).reason,'invalid_event');
assert.equal(r.accept(evt(13,'Y','negative'),19100).command,'VOLUME_DOWN');
assert.equal(r.accept(evt(12),19200).reason,'duplicate_or_stale');
assert.throws(()=>r.arm(1),/non-monotonic/);
assert.throws(()=>new ControlRouter({armWindowMs:60}),/invalid router timing/);
assert.throws(()=>new ControlRouter({minCommandGapMs:-1}),/invalid router timing/);
const rp=new ControlRouter({minCommandGapMs:0});
const expected=[['X','positive','NEXT'],['X','negative','PREVIOUS'],['Y','positive','VOLUME_UP'],
 ['Y','negative','VOLUME_DOWN'],['Z','positive','PLAY_PAUSE']];
for(let i=0;i<expected.length;i++){
 const [axis,direction,command]=expected[i],ms=2000+i*3000;
 rp.arm(ms);assert.equal(rp.accept(evt(100+i,axis,direction),ms+100).command,command);
}
assert.deepEqual(expected.map(x=>x[2]),MUSIC_COMMANDS);
const p=new VirtualPlayer();
assert.equal(p.snapshot().playing,false);
assert.equal(p.apply('NEXT').track_number,2);
assert.equal(p.apply('PREVIOUS').track_number,1);
assert.equal(p.apply('PLAY_PAUSE').playing,true);
for(let i=0;i<30;i++)p.apply('VOLUME_UP');assert.equal(p.snapshot().volume,100);
for(let i=0;i<30;i++)p.apply('VOLUME_DOWN');assert.equal(p.snapshot().volume,0);
assert.throws(()=>p.apply('SHELL_COMMAND'),/non-allowlisted/);
const gy=(ms,x)=>({schema:1,timestamp_ns:ms*1e6,gyro_rads:[x,0,0],quat_xyzw:[0,0,0,1]});
const eng=new GestureEngine(), live=new ControlRouter(), player=new VirtualPlayer();
live.arm(2500);eng.process(gy(1000,3));const raw=eng.process(gy(1200,3.4));
assert.equal(raw?.type,'wrist_flick');
const decision=live.accept(raw,2600);assert.equal(decision.command,'NEXT');
assert.equal(player.apply(decision.command).track_number,2);
assert.equal(live.accept(raw,2700).reason,'duplicate_or_stale');
